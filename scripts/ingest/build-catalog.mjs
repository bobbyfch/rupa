// Compile curated works + collect shard stats into public/offline/index/{works,manifest}.json and the rights ledger.
// Usage: node scripts/ingest/build-catalog.mjs
import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';

const ROOT = path.resolve(import.meta.dirname, '../..');
const INDEX = path.join(ROOT, 'public/offline/index');
const slug = value => value.normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const scriptOf = value => /[぀-ヿ]/.test(value) ? 'ja' : /[가-힯]/.test(value) ? 'ko' : /[一-鿿]/.test(value) ? 'zh' : 'latin';
const today = new Date().toISOString().slice(0, 10);

const curated = JSON.parse(await readFile(path.join(ROOT, 'data/curated/works.json'), 'utf8'));
const ids = new Set(), byTitle = new Map(), works = [];
for (const [category, collection, kind, title, year, creators, aliases] of curated.works) {
  let id = `work:${category}:${slug(title)}`;
  if (ids.has(id)) throw new Error(`duplicate work id ${id}`);
  ids.add(id);
  const work = { id, category, collection, kind, title, ...(year ? { year } : {}), ...(creators ? { creators } : {}), aliases: [...new Set(aliases)].map(value => ({ value, script: scriptOf(value) })) };
  works.push(work); byTitle.set(title, work);
}
const editions = curated.editions.map(edition => {
  const work = byTitle.get(edition.work);
  if (!work) throw new Error(`edition references unknown work: ${edition.work}`);
  const { work: _name, ...rest } = edition;
  return { id: `ed:${slug(edition.work)}:${edition.region.toLowerCase()}:${edition.year}`, workId: work.id, ...rest };
});
const collections = [...new Map(works.map(work => [work.collection, { id: work.collection, label: work.collection.replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase()), category: work.category }])).values()];
await writeFile(path.join(INDEX, 'works.json'), JSON.stringify({ schemaVersion: 1, generatedAt: today, works, editions, themes: curated.themes, facets: curated.facets, collections }));

const shards = [];
for (const file of (await readdir(INDEX)).sort()) {
  if (!/^(games-.+|anime|wd-.+|audiobooks)\.json$/.test(file)) continue;
  const data = JSON.parse(await readFile(path.join(INDEX, file), 'utf8'));
  const bytes = (await stat(path.join(INDEX, file))).size;
  shards.push({ id: file.replace(/\.json$/, ''), kind: data.kind, ...(data.platform ? { platform: data.platform, label: data.label } : {}), ...(data.category ? { category: data.category } : {}), file, rows: data.rows.length + (data.serials?.rows.length || 0), bytes, revision: data.source.revision || data.generatedAt, sourceRepo: data.source.repo, sourceId: data.source.id, sourceUrl: data.source.url, rights: data.rights });
}
shards.unshift({ id: 'works', kind: 'works', file: 'works.json', rows: works.length, bytes: (await stat(path.join(INDEX, 'works.json'))).size });
await writeFile(path.join(INDEX, 'manifest.json'), JSON.stringify({ schemaVersion: 1, generatedAt: today, shards }));

// Public source status for the in-app Sources & rights panel (registry minus internal probe details).
const registry = JSON.parse(await readFile(path.join(ROOT, 'data/registry/sources.json'), 'utf8'));
const artForCount = JSON.parse(await readFile(path.join(ROOT, 'public/offline/artworks.json'), 'utf8'));
const mirroredBySource = {};
for (const asset of artForCount.assets) { const id = asset.sourceId || 'cleveland-cc0'; mirroredBySource[id] = (mirroredBySource[id] || 0) + 1; }
const linkOnly = JSON.parse(await readFile(path.join(ROOT, 'data/curated/link-only.json'), 'utf8')).archives;
await writeFile(path.join(INDEX, 'sources.json'), JSON.stringify({ generatedAt: today, linkOnly, sources: registry.sources.map(s => ({ id: s.id, name: s.name, role: s.role, status: s.status, rightsMode: s.rightsMode, imageMode: s.imageMode, upstream: s.upstream, lastChecked: s.lastChecked, notes: s.notes, mirrored: mirroredBySource[s.id] || 0 })) }));

// Human-readable attribution list for every mirrored file (docs/ATTRIBUTIONS.md), generated from the manifest so it cannot drift.
{
  const rows = [...artForCount.assets].sort((a, b) => (a.source + a.title).localeCompare(b.source + b.title));
  const lines = ['# Attributions', '', 'Generated by `npm run ingest:catalog` from `public/offline/artworks.json`. Every file below ships inside RUPA under the licence shown; the evidence link is the record that states it.', '',
    '| Work | Source | Licence | Evidence |', '|---|---|---|---|',
    ...rows.map(a => '| ' + [a.title.replace(/\|/g, '/'), a.source, a.licenseLabel || a.rightsStatus || 'CC0', '[record](' + (a.rightsEvidenceUrl || a.sourceUrl) + ')'].join(' | ') + ' |'), '',
    rows.length + ' files.', ''];
  await writeFile(path.join(ROOT, 'docs/ATTRIBUTIONS.md'), lines.join('\n'));
}

// Rights ledger: one row per mirrored binary (hash verified later by verify-assets) plus one row per metadata-only shard.
const art = JSON.parse(await readFile(path.join(ROOT, 'public/offline/artworks.json'), 'utf8'));
const ledger = [];
for (const asset of art.assets) {
  for (const [role, rel, bytesKey] of [['print', asset.downloadUrl, 'fileBytes'], ['web', asset.previewUrl, 'previewBytes']]) {
    if (role === 'web' && rel === asset.downloadUrl) continue; // preview is the print file itself
    const file = path.join(ROOT, 'public', rel);
    const buffer = await readFile(file);
    ledger.push({
      path: `public/${rel}`, role, assetId: asset.id, sha256: createHash('sha256').update(buffer).digest('hex'), bytes: buffer.length, expectedBytes: asset[bytesKey],
      sourceId: asset.sourceId || 'cleveland-cc0', sourceUrl: asset.sourceUrl, rightsStatus: asset.rightsStatus || 'cc0', licenseUrl: asset.licenseUrl, rightsNote: asset.rightsNote,
      rightsEvidenceUrl: asset.rightsEvidenceUrl || asset.sourceUrl, attribution: asset.attribution, upstreamRevision: asset.upstreamRevision || art.generatedAt, checkedAt: asset.checkedAt || art.generatedAt, ingestedAt: asset.ingestedAt || asset.checkedAt || art.generatedAt,
      mirrored: true,
    });
  }
}
for (const shard of shards.filter(s => s.kind !== 'works')) {
  ledger.push({ path: `public/offline/index/${shard.file}`, role: 'metadata-shard', sourceId: shard.kind === 'anime' ? 'anime-offline-database' : shard.kind === 'games' ? 'libretro-thumbnails' : shard.sourceId, sourceUrl: shard.sourceRepo ? `https://github.com/${shard.sourceRepo}` : shard.sourceUrl, rightsStatus: 'reference-only', upstreamRevision: shard.revision, checkedAt: today, mirrored: false });
}
await writeFile(path.join(ROOT, 'data/provenance/rights-ledger.json'), JSON.stringify({ schemaVersion: 1, generatedAt: today, entries: ledger }, null, 1) + '\n');
console.log({ works: works.length, editions: editions.length, shards: shards.length, ledger: ledger.length });
